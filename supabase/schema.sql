create or replace function approve_loan(
  p_id_pinjam integer,
  p_id_admin integer,
  p_durasi_hari integer default 7
)
returns peminjaman
language plpgsql
security definer
as $$
declare
  v_loan peminjaman;
  v_stock integer;
begin
  select * into v_loan
  from peminjaman
  where id_pinjam = p_id_pinjam
  for update;

  if not found then
    raise exception 'Peminjaman tidak ditemukan';
  end if;

  if v_loan.status_peminjaman <> 'menunggu' then
    raise exception 'Peminjaman sudah diproses';
  end if;

  select stok into v_stock
  from buku
  where id_buku = v_loan.id_buku
  for update;

  if coalesce(v_stock, 0) <= 0 then
    raise exception 'Stok buku habis';
  end if;

  update buku
  set stok = stok - 1
  where id_buku = v_loan.id_buku;

  update peminjaman
  set
    id_admin = p_id_admin,
    status_peminjaman = 'disetujui',
    tanggal_pinjam = current_date,
    tanggal_jatuh_tempo = current_date + greatest(p_durasi_hari, 1),
    alasan_ditolak = null
  where id_pinjam = p_id_pinjam
  returning * into v_loan;

  return v_loan;
end;
$$;

create or replace function return_loan(
  p_id_pinjam integer,
  p_id_admin integer
)
returns peminjaman
language plpgsql
security definer
as $$
declare
  v_loan peminjaman;
begin
  select * into v_loan
  from peminjaman
  where id_pinjam = p_id_pinjam
  for update;

  if not found then
    raise exception 'Peminjaman tidak ditemukan';
  end if;

  if v_loan.status_peminjaman not in ('disetujui', 'dipinjam') then
    raise exception 'Peminjaman tidak aktif';
  end if;

  update peminjaman
  set
    id_admin = p_id_admin,
    status_peminjaman = 'dikembalikan',
    tanggal_kembali_real = current_date
  where id_pinjam = p_id_pinjam
  returning * into v_loan;

  update buku
  set stok = stok + 1
  where id_buku = v_loan.id_buku;

  insert into pengembalian (id_admin, tanggal_kembali, id_pinjam)
  values (p_id_admin, current_date, p_id_pinjam)
  on conflict (id_pinjam)
  do update set id_admin = excluded.id_admin, tanggal_kembali = excluded.tanggal_kembali;

  insert into riwayat (id_pinjam)
  values (p_id_pinjam)
  on conflict (id_pinjam) do nothing;

  return v_loan;
end;
$$;

create or replace function approve_extension(
  p_id_perpanjangan integer,
  p_id_admin integer
)
returns perpanjangan
language plpgsql
security definer
as $$
declare
  v_extension perpanjangan;
  v_loan peminjaman;
begin
  select * into v_extension
  from perpanjangan
  where id_perpanjangan = p_id_perpanjangan
  for update;

  if not found then
    raise exception 'Perpanjangan tidak ditemukan';
  end if;

  if v_extension.status_perpanjangan <> 'menunggu' then
    raise exception 'Perpanjangan sudah diproses';
  end if;

  select * into v_loan
  from peminjaman
  where id_pinjam = v_extension.id_pinjam
  for update;

  if v_loan.status_peminjaman not in ('disetujui', 'dipinjam') then
    raise exception 'Peminjaman tidak aktif';
  end if;

  update peminjaman
  set tanggal_jatuh_tempo = coalesce(tanggal_jatuh_tempo, current_date) + v_extension.durasi_perpanjangan
  where id_pinjam = v_extension.id_pinjam;

  update perpanjangan
  set
    id_admin = p_id_admin,
    status_perpanjangan = 'disetujui',
    tanggal_perpanjangan = current_date,
    alasan_ditolak = null
  where id_perpanjangan = p_id_perpanjangan
  returning * into v_extension;

  return v_extension;
end;
$$;

