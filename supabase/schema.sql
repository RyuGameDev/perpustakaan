create table admin (
  id_admin integer generated by default as identity primary key,
  nama_admin varchar(100) not null,
  email_admin varchar(100) not null unique,
  password_hash text not null,
  jabatan varchar(80) default 'Petugas Perpustakaan',
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table mahasiswa (
  npm varchar(20) primary key,
  nama varchar(100) not null,
  email varchar(100) not null unique,
  password_hash text not null,
  nomor_induk varchar(40),
  jurusan varchar(100),
  no_telepon varchar(30),
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table buku (
  id_buku integer generated by default as identity primary key,
  judul varchar(160) not null,
  penulis varchar(120) not null,
  penerbit varchar(120),
  tahun_terbit integer,
  isbn varchar(30),
  kategori varchar(80),
  lokasi_rak varchar(40),
  stok integer not null default 0 check (stok >= 0),
  cover_url text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table peminjaman (
  id_pinjam integer generated by default as identity primary key,
  npm varchar(20) not null references mahasiswa(npm) on delete restrict on update cascade,
  id_buku integer not null references buku(id_buku) on delete restrict on update cascade,
  id_admin integer references admin(id_admin) on delete set null on update cascade,
  tanggal_pinjam date,
  tanggal_jatuh_tempo date,
  tanggal_kembali_real date,
  status_peminjaman varchar(20) not null default 'menunggu'
    check (status_peminjaman in ('menunggu', 'disetujui', 'ditolak', 'dipinjam', 'dikembalikan')),
  alasan_ditolak text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table pengembalian (
  id_kembali integer generated by default as identity primary key,
  id_admin integer references admin(id_admin) on delete set null on update cascade,
  tanggal_kembali date not null default current_date,
  id_pinjam integer not null unique references peminjaman(id_pinjam) on delete restrict on update cascade,
  created_at timestamptz default now()
);

create table perpanjangan (
  id_perpanjangan integer generated by default as identity primary key,
  id_admin integer references admin(id_admin) on delete set null on update cascade,
  id_pinjam integer not null references peminjaman(id_pinjam) on delete restrict on update cascade,
  tanggal_perpanjangan date,
  durasi_perpanjangan integer not null default 7 check (durasi_perpanjangan between 1 and 30),
  status_perpanjangan varchar(20) not null default 'menunggu'
    check (status_perpanjangan in ('menunggu', 'disetujui', 'ditolak')),
  alasan_ditolak text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table riwayat (
  id_riwayat integer generated by default as identity primary key,
  id_pinjam integer not null unique references peminjaman(id_pinjam) on delete restrict on update cascade,
  created_at timestamptz default now()
);

create table notifikasi (
  id_notif integer generated by default as identity primary key,
  npm varchar(20) references mahasiswa(npm) on delete cascade on update cascade,
  id_admin integer references admin(id_admin) on delete cascade on update cascade,
  target_role varchar(20) not null check (target_role in ('mahasiswa', 'admin')),
  email_tujuan varchar(100) not null,
  pesan text not null,
  jenis varchar(40) not null default 'status',
  tanggal_notif timestamptz not null default now(),
  sudah_dibaca boolean not null default false,
  email_status varchar(30) not null default 'pending',
  sent_at timestamptz,
  created_at timestamptz default now()
);

create index idx_buku_judul on buku using gin (to_tsvector('simple', judul || ' ' || penulis || ' ' || coalesce(kategori, '')));
create index idx_peminjaman_npm on peminjaman(npm);
create index idx_peminjaman_status on peminjaman(status_peminjaman);
create index idx_peminjaman_jatuh_tempo on peminjaman(tanggal_jatuh_tempo);
create index idx_perpanjangan_status on perpanjangan(status_perpanjangan);
create index idx_notifikasi_mahasiswa on notifikasi(npm, sudah_dibaca);
create index idx_notifikasi_admin on notifikasi(id_admin, sudah_dibaca);

create or replace function set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

